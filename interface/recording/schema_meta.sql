  primary key (run_id, dimension)
);

create table snapshot (
  run_id int4 not null references run,
  seq int4 not null,
  phase text not null check (phase in ('start', 'post_action', 'post_run')),
  game_date game_hours not null,
  taken_at timestamptz not null,
  read_ms float4 not null,
  local_date_time int8 not null,
  paused bool,
  speed int4,
  ui_panel_open bool not null,
  ui_interaction_open bool not null,
  ui_map_list_open bool not null,
  primary key (run_id, seq),
  check ((paused is null) = (speed is null))
);

create table catalogue_action (
  action int4 primary key references action
);

create table action_parameter (
  action int4 not null references action,
  name text not null,
  value_kind text not null check (value_kind in ('integer', 'text')),
  primary key (action, name)
);

create table loop_action (
  run_id int4 not null references run,
  n int4 not null,
  turn int4 not null,
  advisor int4 not null references advisor,
  action int4 not null references action,
  before_seq int4 not null,
  after_seq int4,
  status text not null check (status in ('done', 'invalid', 'raced', 'no_object', 'ui_leftover')),
  detail text,
  ms int4,
  logged_at timestamptz not null,
  primary key (run_id, n),
  unique (run_id, n, action),
  foreign key (run_id, before_seq) references snapshot,
  foreign key (run_id, after_seq) references snapshot
);

create table loop_action_param (
  run_id int4 not null,
  n int4 not null,
  action int4 not null,
  name text not null,
  integer_value int8,
  text_value text,
  primary key (run_id, n, name),
  foreign key (run_id, n, action) references loop_action (run_id, n, action),
  foreign key (action, name) references action_parameter,
  check ((integer_value is null) <> (text_value is null))
);
