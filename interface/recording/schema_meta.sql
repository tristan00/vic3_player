create table world (
  world_id int4 generated by default as identity primary key,
  digest bytea not null unique
);

create table world_province (
  world_id int4 not null references world,
  color int4 not null,
  state_region int2 references state_region,
  terrain int2 references terrain,
  area_pixels int4 not null,
  x float8 not null,
  y float8 not null,
  primary key (world_id, color)
);

create table world_adjacency (
  world_id int4 not null,
  first_color int4 not null,
  second_color int4 not null,
  shared_border_pixels int4 not null,
  primary key (world_id, first_color, second_color),
  foreign key (world_id, first_color) references world_province,
  foreign key (world_id, second_color) references world_province,
  check (first_color < second_color)
);

create table world_asset (
  world_id int4 not null references world,
  name text not null,
  data bytea not null,
  primary key (world_id, name)
);

create table ruleset (
  ruleset_id int4 generated by default as identity primary key,
  digest bytea not null unique
);

create table ruleset_definition (
  ruleset_id int4 not null references ruleset,
  folder text not null,
  position int4 not null,
  name text not null,
  primary key (ruleset_id, folder, position),
  unique (ruleset_id, folder, name)
);

create table game_definition (
  ruleset_id int4 not null,
  folder text not null,
  name text not null,
  field text not null,
  position int2 not null,
  value text not null,
  primary key (ruleset_id, folder, name, field, position),
  foreign key (ruleset_id, folder, name) references ruleset_definition (ruleset_id, folder, name)
);

create table event_definition_option (
  ruleset_id int4 not null references ruleset,
  event_type int2 not null references event_type,
  option int2 not null,
  name text,
  has_trigger bool not null,
  default_option bool not null,
  primary key (ruleset_id, event_type, option)
);

create table building_production_method (
  ruleset_id int4 not null references ruleset,
  building_type int2 not null references building_type,
  production_method_group int2 not null references production_method_group,
  production_method int2 not null references production_method,
  primary key (ruleset_id, building_type, production_method_group, production_method)
);

create table production_method_goods (
  ruleset_id int4 not null references ruleset,
  production_method int2 not null references production_method,
  goods int2 not null references goods,
  direction text not null check (direction in ('input', 'output')),
  scaling text not null check (scaling in ('workforce_scaled', 'level_scaled', 'throughput_scaled', 'unscaled')),
  amount float8 not null,
  primary key (ruleset_id, production_method, goods, direction, scaling)
);

create table production_method_employment (
  ruleset_id int4 not null references ruleset,
  production_method int2 not null references production_method,
  pop_type int2 not null references pop_type,
  scaling text not null check (scaling in ('workforce_scaled', 'level_scaled', 'throughput_scaled', 'unscaled')),
  amount float8 not null,
  primary key (ruleset_id, production_method, pop_type, scaling)
);

create table production_method_modifier (
  ruleset_id int4 not null references ruleset,
  production_method int2 not null references production_method,
  target text not null check (target in ('building', 'state', 'country')),
  scaling text not null check (scaling in ('workforce_scaled', 'level_scaled', 'throughput_scaled', 'unscaled')),
  modifier text not null,
  value float8 not null,
  primary key (ruleset_id, production_method, target, scaling, modifier)
);

create table production_method_requirement (
  ruleset_id int4 not null references ruleset,
  production_method int2 not null references production_method,
  kind text not null,
  key text not null,
  primary key (ruleset_id, production_method, kind, key)
);

create table production_method_profession_ratio (
  ruleset_id int4 not null references ruleset,
  production_method int2 not null references production_method,
  pop_type int2 not null references pop_type,
  ratio float8 not null,
  primary key (ruleset_id, production_method, pop_type)
);

create table dlc (
  ruleset_id int4 not null references ruleset,
  name text not null,
  primary key (ruleset_id, name)
);

create table capture_gap (
  ruleset_id int4 not null references ruleset,
  kind text not null check (kind in ('alert_unevaluated', 'production_method_undetermined', 'script_absent_reference')),
  subject text not null,
  detail text not null,
  primary key (ruleset_id, kind, subject, detail)
);

create table budget_line (
  direction text not null check (direction in ('income', 'expense')),
  line int2 not null,
  name text,
  primary key (direction, line),
  unique (direction, name)
);

create table run (
  run_id int4 generated always as identity primary key,
  kind text not null check (kind in ('mini', 'vanilla')),
  source_session text not null,
  started_at timestamptz not null,
  heartbeat_at timestamptz not null,
  progress_at timestamptz not null,
  progress_step text not null,
  longest_step text,
  longest_step_ms int4,
  ended_at timestamptz,
  end_reason text check (end_reason in ('time', 'years', 'defeated', 'debt_cap', 'ui_stuck', 'game_crashed', 'loop_crashed', 'loop_lost', 'loop_stalled')),
  end_detail text,
  game_exited_at timestamptz,
  world_id int4 not null references world,
  ruleset_id int4 not null references ruleset,
  player_country int4 not null,
  game_speed int2 not null,
  first_start bool not null,
  custom_rng_seed text not null,
  tag int2 not null references country_definition,
  world_file text not null,
  cli_seed int8 not null,
  run_seed int8 not null,
  years float8 not null,
  minutes float8 not null,
  profile text not null,
  pool int4 not null,
  runs_requested int4 not null,
  world_seed int8,
  countries int2,
  states int2,
  tech float8,
  pop float8,
  picker text not null check (picker in ('first', 'catboost')),
  candidates int2 not null check (candidates >= 1),
  objective_gdp float8 not null check (objective_gdp between 0 and 1),
  objective_population float8 not null check (objective_population between 0 and 1),
  objective_sol float8 not null check (objective_sol between 0 and 1),
  objective_alpha float8 not null check (objective_alpha between 0 and 1),
  check ((kind = 'mini') = (num_nonnulls(world_seed, countries, states, tech, pop) = 5)),
  check ((kind = 'vanilla') = (num_nulls(world_seed, countries, states, tech, pop) = 5)),
  unique (run_id, world_id),
  check ((ended_at is null) = (end_reason is null)),
  check (end_detail is null or end_reason in ('loop_crashed', 'game_crashed', 'loop_stalled')),
  check ((longest_step is null) = (longest_step_ms is null)),
  check (abs(objective_gdp + objective_population + objective_sol - 1) < 1e-9)
);

create table run_advisor (
